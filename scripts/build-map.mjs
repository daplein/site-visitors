// Builds site/world.svg: one <path data-cc="IE"> per country (ISO 3166-1 alpha-2, the same
// codes as Cloudflare's request.cf.country) and one bubble anchor per country.
//
// Shapes come from Natural Earth 1:110m (small file). Anchors come from 1:50m, which also
// has tiny countries (Malta, Singapore…) so every country gets a bubble position. An anchor
// is the centroid of the country's largest landmass, so France's sits in France, not
// somewhere between Paris and French Guiana.
//
// Country names are left out: the stats page gets them from Intl.DisplayNames.
// Natural Earth is public domain. Run: npm run map
import { geoArea, geoCentroid, geoEqualEarth, geoPath } from "d3-geo";
import countries from "i18n-iso-countries";
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const WIDTH = 960;
const atlas = (scale) => JSON.parse(readFileSync(new URL(`../node_modules/world-atlas/countries-${scale}.json`, import.meta.url)));
const BY_NAME = { Kosovo: "XK" };   // no ISO numeric code in Natural Earth
const SKIP = new Set(["AQ"]);       // Antarctica: lots of space, no visitors

function features(scale) {
  const topo = atlas(scale);
  return feature(topo, topo.objects.countries).features
    .map((f) => ({ ...f, cc: (f.id && countries.numericToAlpha2(f.id)) || BY_NAME[f.properties.name] }))
    .filter((f) => f.cc && !SKIP.has(f.cc));
}

const shapes = features("110m");
const projection = geoEqualEarth().fitWidth(WIDTH, { type: "FeatureCollection", features: shapes });
const path = geoPath(projection).digits(1);
const [[, y0], [, y1]] = path.bounds({ type: "FeatureCollection", features: shapes });
const height = Math.ceil(y1 + Math.max(0, -y0));

function largestPart(f) {
  if (f.geometry.type !== "MultiPolygon") return f;
  const parts = f.geometry.coordinates.map((coordinates) => ({ type: "Polygon", coordinates }));
  return parts.reduce((a, b) => (geoArea(b) > geoArea(a) ? b : a));
}

const anchors = new Map();
for (const f of features("50m")) {
  const [x, y] = projection(geoCentroid(largestPart(f)));
  if (!anchors.has(f.cc)) anchors.set(f.cc, [x.toFixed(1), y.toFixed(1)]);
}


const svg = [
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 ${Math.floor(Math.min(0, y0))} ${WIDTH} ${height}" role="img" aria-label="World map of visitors">`,
  `<!-- Generated by scripts/build-map.mjs from Natural Earth 1:110m / 1:50m (public domain). -->`,
  `<g class="countries">`,
  ...shapes.map((f) => `<path data-cc="${f.cc}" d="${path(f)}"/>`),
  `</g>`,
  `<g class="anchors" display="none">`,
  ...[...anchors].map(([cc, [x, y]]) => `<circle data-cc="${cc}" cx="${x}" cy="${y}" r="0"/>`),
  `</g>`,
  `</svg>`,
].join("\n");

writeFileSync(new URL("../site/world.svg", import.meta.url), svg + "\n");
console.log(`site/world.svg: ${shapes.length} shapes, ${anchors.size} anchors, ${(svg.length / 1024).toFixed(0)} KB`);
